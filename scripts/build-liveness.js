// Hermes bytecode does not retain Function#toString source. Embed ordinary JS at build time.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.join(__dirname, '..');
function buildSource() {
  return ts.transpileModule(fs.readFileSync(path.join(root, 'src/livenessTracker.ts'), 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: true },
  }).outputText.replace(/^export /gm, '').trim();
}
function generate() {
  fs.writeFileSync(path.join(root, 'src/livenessTrackerSource.ts'), '// Generated by scripts/build-liveness.js; edit livenessTracker.ts instead.\nexport const LIVENESS_FACTORY_SOURCE=' + JSON.stringify(buildSource()) + ';\n');
}
module.exports = {buildSource, generate};
if (require.main === module) generate();
